    /// <summary>撞杯时 ×8 和 ×4 的比例（新一轮开始的重弹珠：×2 .344、×4 .108、×8 .007）。</summary>
    private const double R48 = 0.007 / 0.108;
    private static readonly double[] F0 = Fresh();
    private static readonly double[] F0Cdf = Cumulative(F0);
    private static readonly double D0 = (1.0 - QQ[0]) / QQ[0] * QC[0];
    private static readonly double[] Pow2 = Powers(0.0), Pow2Light = Powers(-D0);

    /// <summary>撞杯时 log2 倍数是 1 / 2 / 3 的概率，均值 = c（×4 : ×8 的比例不变）。</summary>
    private static void Split(double c, out double s2, out double s4, out double s8)
    {
        s4 = Math.Clamp((c - 1.0) / (1.0 + 2.0 * R48), 0.0, 1.0);
        s8 = R48 * s4;
        s2 = 1.0 - s4 - s8;
    }

    /// <summary>新一轮开始的重弹珠：进槽前总共还翻几次（D）的分布。</summary>
    private static double[] Fresh()
    {
        Split(QC[0], out double s2, out double s4, out double s8);
        double q0 = QQ[0];
        var f = new double[DMax + 1];
        f[0] = q0;
        for (int d = 1; d <= DMax; d++)
            f[d] = (1.0 - q0) * (s2 * f[d - 1] + (d >= 2 ? s4 * f[d - 2] : 0.0) + (d >= 3 ? s8 * f[d - 3] : 0.0));
        return f;
    }

    private static double[] Cumulative(double[] f)
    {
        var c = new double[f.Length];
        double a = 0.0;
        for (int i = 0; i < f.Length; i++) c[i] = a += f[i];
        return c;
    }

    private static double[] Powers(double shift)
    {
        var p = new double[DMax + 1];
        for (int d = 0; d <= DMax; d++) p[d] = Math.Pow(2.0, d + shift);
        return p;
    }

    private static double Interp(double[] a, double x)
    {
        double u = x / QStep;
        int i = Math.Min((int)u, a.Length - 2);
        return a[i] + (a[i + 1] - a[i]) * (u - i);
    }

    /// <summary>这一轮已经走了 tau 秒的重弹珠：D 的累积分布。</summary>
    private static void CdfTau(double tau, double[] cdf)
    {
        tau = Math.Clamp(tau, 0.0, QStep * (QQ.Length - 1));
        double q = Interp(QQ, tau);
        Split(Interp(QC, tau), out double s2, out double s4, out double s8);
        double a = 0.0;
        for (int d = 0; d <= DMax; d++)
        {
            double f = (1.0 - q) * ((d >= 1 ? s2 * F0[d - 1] : 0.0) + (d >= 2 ? s4 * F0[d - 2] : 0.0) + (d >= 3 ? s8 * F0[d - 3] : 0.0));
            if (d == 0) f += q;
            cdf[d] = a += f;
        }
        cdf[DMax] = 1.0;
    }

    /// <summary>这一轮 进槽 / ×2 / ×4 / ×8 的概率是 p 的重弹珠：D 的累积分布（撞杯以后是新的一轮，按 F0 散开）。</summary>
    private static void CdfPos(double[] p, double[] cdf)
    {
        double a = 0.0;
        for (int d = 0; d <= DMax; d++)
        {
            double f = (d >= 1 ? p[1] * F0[d - 1] : 0.0) + (d >= 2 ? p[2] * F0[d - 2] : 0.0) + (d >= 3 ? p[3] * F0[d - 3] : 0.0);
            if (d == 0) f += p[0];
            cdf[d] = a += f;
        }
        cdf[DMax] = 1.0;
    }

