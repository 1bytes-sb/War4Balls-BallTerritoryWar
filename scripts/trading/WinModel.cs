        x[8] = L(balls);
        x[9] = L(bullets);
        x[10] = L(v[t, NearBalls]);
        x[11] = L(v[t, NearBullets]);
        x[12] = v[t, Revived] < 0.5 && v[t, MarbleCount] > 0.5 ? 1.0 : 0.0;
        x[13] = v[t, Reviving];
        // 额外弹珠连续算：充能条满了生出一颗弹珠时不跳（充能进度算成小数颗）
        x[14] = Math.Log(1.0 + v[t, Extra] + Math.Clamp(v[t, Charge] / Math.Max(v[t, ChargeThreshold], 1.0), 0.0, 1.0));
        return field;
    }

    /// <summary>当前局面下每队的获胜概率（被淘汰的是 0），和为 1。s 不为 null 时把这次的局面留下（给 Effects 用）。</summary>
    public static void Probabilities(RightArena r, LeftArena l, double[] p, Snap s = null)
    {
        s ??= new Snap();
        Snapshot(r, l, s.V);
        MarbleSamples(l, Main.GameTime, s);
        Probabilities(s, p);
    }

    private static readonly double[,] _v1 = new double[Main.TeamCount, VCount], _m1 = new double[Main.TeamCount, Samples];
    private static readonly double[] _p1 = new double[Main.TeamCount];

    /// <summary>
    /// 带进槽预判的胜率：先算不预判的 P0（留在 s.P0），再对每颗快进槽的重弹珠，
    /// 按 q(槽) 加上「它的数值从弹珠样本里拿掉、加进那个槽的原始数值」以后的胜率变化。
    /// </summary>
    public static void Probabilities(Snap s, double[] p)
    {
        int n = Main.TeamCount;
        Probabilities(s.V, s.M, s.P0);
        Array.Copy(s.P0, p, n);
        for (int z = 0; z < s.ZoneCount; z++)
        {
            var (team, v, q) = s.Zone[z];
            if (s.V[team, Alive] < 0.5) continue;
            var c = s.C[z];
            Array.Copy(s.M, _m1, s.M.Length);
            for (int k = 0; k < Samples; k++) _m1[team, k] = Math.Max(_m1[team, k] - c[k], 0.0);
            for (int slot = 0; slot < 5; slot++)
            {
                double w = SlotQ[q + slot];
                if (w < 1e-4) continue;
                Array.Copy(s.V, _v1, s.V.Length);
                _v1[team, SlotCol[slot]] += v;
                Probabilities(_v1, _m1, _p1);
                for (int t = 0; t < n; t++) p[t] += w * (_p1[t] - s.P0[t]);
            }
        }
    }

    private static readonly double[] _x = new double[FeatureCount];
    private static readonly double[] _b = new double[Main.TeamCount], _field = new double[Main.TeamCount],
        _z = new double[Main.TeamCount], _acc = new double[Main.TeamCount], _a = new double[Main.TeamCount];

    /// <summary>
    /// 由原始数值 v 和弹珠样本 m 算获胜概率：v[t, Alive] = 1 的阵营之间，每个样本做一次 softmax(τ·分数 + log a)，取平均，再混进按 a 分的 ε 保底。
    /// </summary>
    public static void Probabilities(double[,] v, double[,] m, double[] p)
    {
        int n = Main.TeamCount, alive = 0;
        double terr = 0.0, sa = 0.0, kb = 0.0;
        for (int t = 0; t < n; t++)
        {
            if (v[t, Alive] < 0.5) continue;
            terr += v[t, Territory];
            alive++;
        }
        if (alive == 0)
        {
            Array.Clear(p);
            return;
        }
        var sw = alive <= 2 ? StatusWeight2 : StatusWeight;
        for (int t = 0; t < n; t++)
        {
            if (v[t, Alive] < 0.5) continue;
            int st = Status(v, t);
            _a[t] = st == 3 ? LandWeight(v[t, Landed], alive) : sw[st];
            sa += _a[t];
            kb += st == 4 ? StatusWeight[4] : 1.0;
        }
        Array.Copy(Tau, _tau, 5);
        double u = Math.Clamp((_simTime - 600.0) / 300.0, -2.0, 2.0);
        _tau[4] *= Math.Exp((u < 0.0 ? Tau4SlopeEarly : Tau4Slope) * u);
        double tau = alive >= 4 ? Lerp(_tau, Math.Clamp(kb, 3.0, 4.0)) : _tau[Math.Max(alive, 2)], eps = Lerp(Mix, sa);
        for (int t = 0; t < n; t++)
        {
            _acc[t] = 0.0;
            if (v[t, Alive] < 0.5) continue;
            _field[t] = Features(v, t, terr > 0.0 ? v[t, Territory] / terr : 0.25, _x);
            double sc = 0.0;
            for (int k = 0; k < FeatureCount; k++)
                if (k != TotalIndex) sc += W[k] * _x[k];
            _b[t] = sc;
        }
        for (int s = 0; s < Samples; s++)
        {
            double max = double.NegativeInfinity;
            for (int t = 0; t < n; t++)
            {
                if (v[t, Alive] < 0.5) continue;
                _z[t] = tau * (_b[t] + W[TotalIndex] * L(_field[t] + m[t, s])) + Math.Log(_a[t]);
                max = Math.Max(max, _z[t]);
            }
            double sum = 0.0;
            for (int t = 0; t < n; t++)
            {
                if (v[t, Alive] < 0.5) continue;
                _z[t] = Math.Exp(_z[t] - max);
                sum += _z[t];
            }
            for (int t = 0; t < n; t++)
                if (v[t, Alive] >= 0.5) _acc[t] += _z[t] / sum;
        }
        for (int t = 0; t < n; t++)
            p[t] = v[t, Alive] >= 0.5 ? (1.0 - eps) * _acc[t] / Samples + eps * _a[t] / sa : 0.0;
    }

