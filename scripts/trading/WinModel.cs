    private static ulong Mix64(ulong z)
    {
        z += 0x9E3779B97F4A7C15UL;
        z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9UL;
        z = (z ^ (z >> 27)) * 0x94D049BB133111EBUL;
        return z ^ (z >> 31);
    }

    /// <summary>
    /// 一颗弹珠的分层样本顺序：同一颗弹珠在同一轮里（队、数值、这一轮开始的时刻都不变）用同一组，价格随时间连续变、不抖；
    /// 不同弹珠的顺序打乱，各队的样本互相独立。
    /// </summary>
    private static void Strata(int team, bool light, float v, float t0, int[] perm)
    {
        ulong s = Mix64(Mix64(Mix64((ulong)(team + (light ? 4 : 0))) ^ (uint)BitConverter.SingleToInt32Bits(v))
                        ^ (uint)BitConverter.SingleToInt32Bits(t0));
        for (int i = 0; i < perm.Length; i++) perm[i] = i;
        for (int i = perm.Length - 1; i > 0; i--)
        {
            s += 0x9E3779B97F4A7C15UL;
            int j = (int)(Mix64(s) % (ulong)(i + 1));
            (perm[i], perm[j]) = (perm[j], perm[i]);
        }
    }

