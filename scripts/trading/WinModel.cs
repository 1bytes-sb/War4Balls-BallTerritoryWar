/// <summary>
/// 资金模式里每个阵营的获胜概率：不光看领地，右侧战场和左侧弹珠台的局面都算进去 ——
/// 领地占比、中心附近的领地、总资源（护盾 + 机枪 / 狙击 / 风暴火力 + 自己的子弹和大球 + 左侧弹珠）、护盾、各项火力、
/// 场上子弹、大球、复活机会、额外弹珠（含充能进度）、压到中心附近的敌方大球和子弹。
/// 模型：活着的阵营之间做 softmax(τ·分数)，分数 = Σ 权重 × 特征（数值类特征取 log(1 + 数值 / 1M)），
/// 再混进一点平均分（ε / 存活队数）；τ、ε 按还活着几队分开。
/// 左侧弹珠只算在总资源里、不单独算：弹珠掉进槽只是把数值挪到火力池，单独算的话胜率会跟着弹珠「长大 → 掉进槽 → 新弹珠再长」
/// 来回锯齿，跌了买、涨了卖稳赚。
/// 弹珠按「进槽前还会翻几倍」的所有可能结果取期望定价（见 MarbleSamples）：低价队的胜率对总资源是凸的，
/// 只代一个平均值进去会系统性偏低，弹珠一翻倍价格就可预测地往上漂（玩家稳赚的主要来源）。
/// 权重、τ、ε 是用 --winlog 跑的对局记录按同样的期望价格拟合的（_frames/s10/efit.py，按局交叉验证）。
/// 资金模式的价格在这个胜率上再加一层「晚段新高加价」（LateBoost，剩 4 队、600 秒后才起作用；[wp] 打的还是没加的胜率）。
/// --winlog：每 WinLogEvery 秒（模拟时间）打一行各队的原始数值（[wl]）、左侧每颗弹珠（[ml]）和模型胜率（[wp]），分出胜负时打一行赢家。
/// </summary>
