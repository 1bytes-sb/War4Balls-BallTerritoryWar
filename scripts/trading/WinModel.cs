    /// <summary>
    /// 每队左侧弹珠总值的 Samples 个样本 m[队, k]（now = 弹珠台的时钟 GameTime）。
    /// log 不为 null 时把每颗弹珠记成一行 [ml]（数值:这一轮开始的时刻:x:y:vx:vy:半径:槽坐标U，核对用）。
    /// 快进槽的重弹珠另外记进 snap.Zone / snap.C（进槽预判用，见 SlotQ）。
    /// </summary>
    public static void MarbleSamples(LeftArena l, float now, Snap snap, StringBuilder log = null)
    {
        var m = snap.M;
        Array.Clear(m);
        snap.Zone.Clear();
        snap.ZoneCount = 0;
        log?.Append("[ml] t=").Append(now.ToString("R", Inv));
        double thr = S.WindMassThreshold * Math.Pow(2.0, now / S.BallSizeDoublingSeconds);
        for (int t = 0; t < Main.TeamCount; t++)
        {
            log?.Append(" |");
            if (l == null) continue;
            l.TeamMarbleList(t, _marbles);
            foreach (var mb in _marbles)
            {
                float v = mb.V, t0 = mb.T0;
                log?.Append(' ').Append(v.ToString("R", Inv)).Append(':').Append(t0.ToString("R", Inv))
                    .Append(':').Append(mb.Pos.X.ToString("R", Inv)).Append(':').Append(mb.Pos.Y.ToString("R", Inv))
                    .Append(':').Append(mb.Vel.X.ToString("R", Inv)).Append(':').Append(mb.Vel.Y.ToString("R", Inv))
                    .Append(':').Append(mb.R.ToString("R", Inv)).Append(':').Append(mb.U.ToString("R", Inv));
                double k = Math.Log2(Math.Max(v, 1.0) / thr);
                bool light = k < 0.0;
                double[] cdf, pw;
                double a;
                if (light)
                {
                    a = Math.Max(v, Math.Pow(2.0, LightL) * thr * Math.Pow(2.0, LightSlope * k));
                    cdf = F0Cdf;
                    pw = Pow2Light;
                }
                else
                {
                    a = v;
                    if (PosProbs(now, mb.Pos.X, mb.Pos.Y, mb.Vel.X, mb.Vel.Y, mb.R, _pp)) CdfPos(_pp, _cdf);
                    else CdfTau(now - t0, _cdf);
                    cdf = _cdf;
                    pw = Pow2;
                }
                double[] c = null;
                if (!light && mb.U >= 0f)
                {
                    int yc = 0;
                    while (yc + 1 < SlotQY.Length && mb.Pos.Y >= SlotQY[yc + 1]) yc++;
                    int ub = Math.Min((int)(mb.U * 10.0), SlotNU - 1);
                    snap.Zone.Add((t, v, (yc * SlotNU + ub) * 5));
                    if (snap.C.Count <= snap.ZoneCount) snap.C.Add(new double[Samples]);
                    c = snap.C[snap.ZoneCount++];
                }
                Strata(t, light, v, t0, _perm);
                for (int s = 0; s < Samples; s++)
                {
                    double u = (_perm[s] + 0.5) / Samples;
                    int d = 0;
                    while (d < DMax && cdf[d] < u) d++;
                    m[t, s] += a * pw[d];
                    if (c != null) c[s] = a * pw[d];
                }
            }
        }
    }

