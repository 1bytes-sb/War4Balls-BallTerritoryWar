    /// <summary>
    /// effect[队, 组] = 现在的胜率（不算进槽预判的 s.P0）− 把这组原始数值在活着的阵营之间拉平（都换成平均值）以后的胜率（0.05 = 5 个百分点；淘汰的队是 0）。
    /// s、p 是 Probabilities 留下的局面和算出的胜率。总资源是各部分加起来的，拉平一组也会跟着改总资源。
    /// </summary>
    public static void Effects(Snap s, double[] p, double[,] effect)
    {
        var u = _flat.V;
        int n = Main.TeamCount, alive = 0;
        for (int t = 0; t < n; t++)
            if (s.V[t, Alive] >= 0.5) alive++;
        for (int g = 0; g < Groups.Length; g++)
        {
            Array.Copy(s.V, u, s.V.Length);
            Array.Copy(s.M, _flat.M, s.M.Length);
            foreach (int k in Groups[g])
            {
                double sum = 0.0;
                for (int t = 0; t < n; t++)
                    if (s.V[t, Alive] >= 0.5) sum += s.V[t, k];
                for (int t = 0; t < n; t++)
                    if (s.V[t, Alive] >= 0.5) u[t, k] = sum / alive;
                if (k != MarbleSum) continue;
                for (int j = 0; j < Samples; j++)
                {
                    double ms = 0.0;
                    for (int t = 0; t < n; t++)
                        if (s.V[t, Alive] >= 0.5) ms += s.M[t, j];
                    for (int t = 0; t < n; t++)
                        if (s.V[t, Alive] >= 0.5) _flat.M[t, j] = ms / alive;
                }
            }
            Probabilities(u, _flat.M, _q);
            for (int t = 0; t < n; t++) effect[t, g] = s.V[t, Alive] >= 0.5 ? s.P0[t] - _q[t] : 0.0;
        }
    }

    /// <summary>
    /// 晚段「新高加价」层（TradePanel 每局一个，加在 Probabilities 的胜率上）：剩 4 队、600 秒后刚创新高、还在大涨的 ≥48% 队，
    /// 后面赢得比上面的胜率多（晚段第一次涨过 50% / 60% 时平均低 3 / 13¢），给它加价，其余队按比例让出。
    /// M = 剩 4 队期间每队的最高价（从开局算），SM = M 的 40 秒指数平均，G = M − SM：刚创新高、涨得多 → G 大，
    /// 不再创新高就按 40 秒衰减，价回落不会让 G 变小（不放大下跌）。
    /// X = A·w(t)·h(M)·r(G)：w = 600→720 秒 0→1；h = M 在 ha→ha+0.001 之间平滑 0→1（约 48% 的台阶）；
    /// r = G 在 g0→g0+gw 之间平滑 0→1（16.5→23.2¢，封顶：大跳不比中跳多抬）。新价 = 价 + X − ΣX·价，夹到 [0.002, 0.998] 再归一
    ///（600 秒前 X = 0，只剩这一步：有队低于 0.2% 时别的队差不到 0.2¢，跟拟合一样）。
    /// 拟合（_frames/s10/lup.py，c[klmnop] 492 局）用的是每秒一行：M、SM 每过一个整秒（模拟时间）提交一次，
    /// 中间每 0.25 秒的更新用上次提交的状态加这一刻的价算、不提交（不然一秒内的尖峰会被 M 记住，加价留着再往回掉）。
    /// 参数冻结在 _frames/s10/frozen_lup.txt（m40），在没看过的 cq 109 局上按事先定的 7 条（rules_cq.txt）检验通过；改了要一起改。
    /// lup.py 的 u 门（u0 9）恒为 1，没写。
    /// </summary>
    public sealed class LateBoost
    {
        private const double A = 0.42215272228865564, Ha = 0.47924975697094635, Hw = 0.0008604451761384191,
            G0 = 0.16542975642391183, Gw = 0.06694531552805322, Wa = 600.0, Wb = 720.0, T = 40.0, Dw = 0.015;

        /// <summary>这次更新用的 M、SM（提交的那次就是新的状态）。</summary>
        public readonly double[] M = new double[Main.TeamCount], SM = new double[Main.TeamCount];
        /// <summary>这次更新有没有提交状态（过了一个整秒）。</summary>
        public bool Committed { get; private set; }

        private readonly double[] _m = new double[Main.TeamCount], _sm = new double[Main.TeamCount], _x = new double[Main.TeamCount];
        private double _last, _next;
        private bool _started;

        /// <summary>p = 这一刻的胜率（被淘汰的是 0），原地改成加价以后的；all4 = 四队都活着；now = 模拟秒。</summary>
        public void Apply(double now, double[] p, bool all4)
        {
            int n = Main.TeamCount;
            if (!_started)
            {
                _started = true;
                Array.Copy(p, M, n);
                Array.Copy(p, SM, n);
                Committed = true;
            }
            else
            {
                double k = 1.0 - Math.Exp(-(now - _last) / T);
                for (int t = 0; t < n; t++)
                {
                    M[t] = all4 ? Math.Max(_m[t], p[t]) : _m[t];
                    SM[t] = _sm[t] + k * (M[t] - _sm[t]);
                }
                Committed = now >= _next;
            }
            if (Committed)
            {
                Array.Copy(M, _m, n);
                Array.Copy(SM, _sm, n);
                _last = now;
                _next = Math.Floor(now) + 1.0;
            }
            if (!all4) return;
            double w = Math.Clamp((now - Wa) / (Wb - Wa), 0.0, 1.0), sx = 0.0, sq = 0.0;
            for (int t = 0; t < n; t++)
            {
                _x[t] = A * w * Unit(M[t], Ha, Hw) * Unit(M[t] - SM[t], G0, Gw);
                sx += _x[t];
            }
            for (int t = 0; t < n; t++)
            {
                p[t] = Math.Clamp(p[t] + _x[t] - sx * p[t], 0.002, 0.998);
                sq += p[t];
            }
            sq = Math.Max(sq, 1e-9);
            for (int t = 0; t < n; t++) p[t] /= sq;
        }

        private static double Softplus(double z) => Math.Max(z, 0.0) + Math.Log(1.0 + Math.Exp(-Math.Abs(z)));

        /// <summary>x 在 lo→lo+w 之间平滑 0→1（两端用宽 Dw 的 softplus 圆角；w 至少 0.001，同 lup.py 的 unit）。</summary>
        private static double Unit(double x, double lo, double w)
        {
            w = Math.Max(Math.Abs(w), 1e-3);
            double hi = lo + w;
            return Dw * (Softplus((x - lo) / Dw) - Softplus((x - hi) / Dw)) / w;
        }
    }
