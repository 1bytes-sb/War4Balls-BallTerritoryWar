    /// <summary>四队的原始数值 v[队, 下标]（下标见上面的常数）。</summary>
    public static void Snapshot(RightArena r, LeftArena l, double[,] v)
    {
        _simTime = r.SimTime;
        var own = new double[4, 4];
        var near = new double[4, 2];
        r.BulletSums(own, near, NearFar, NearClose);
        for (int t = 0; t < Main.TeamCount; t++)
        {
            var f = r.Factions[t];
            int mc = 0;
            double ms = 0.0, mx = 0.0;
            l?.TeamMarbles(t, out mc, out ms, out mx);
            double mine = 0.0, ballsFar = 0.0, ballsClose = 0.0;
            foreach (var b in r.Balls)
            {
                if (b.Dead) continue;
                if (b.Team == t) mine += b.Value;
                else
                {
                    float d = b.Pos.DistanceTo(f.Center);
                    if (d < NearFar) ballsFar += b.Value;
                    if (d < NearClose) ballsClose += b.Value;
                }
            }
            v[t, Alive] = f.Alive ? 1 : 0;
            v[t, Revived] = f.Revived ? 1 : 0;
            v[t, Reviving] = f.Reviving ? 1 : 0;
            v[t, Territory] = r.Field.Count[t];
            v[t, Shield] = f.Shield;
            v[t, MgFire] = f.MgFire;
            v[t, SniperFire] = f.SniperFire;
            v[t, StormFire] = f.StormFire;
            v[t, BigBallFire] = f.BigBallFire;
            v[t, Charge] = f.Charge;
            v[t, ChargeThreshold] = f.ChargeThreshold;
            v[t, Extra] = f.ExtraMarbles;
            v[t, MarbleCount] = mc;
            v[t, MarbleSum] = ms;
            v[t, MarbleMax] = mx;
            v[t, OwnBalls] = mine;
            v[t, NearBalls] = ballsFar;
            v[t, Harvest] = r.HarvestTotal[t];
            v[t, MgBullets] = own[t, 0];
            v[t, PdBullets] = own[t, 1];
            v[t, SniperBullets] = own[t, 2];
            v[t, StormBullets] = own[t, 3];
            v[t, NearBullets] = near[t, 0];
            v[t, CloseBullets] = near[t, 1];
            v[t, CloseBalls] = ballsClose;
            v[t, LocalTerritory] = LocalShare(r.Field, f.Center, t);
            v[t, Landed] = f.LandTime >= 0f ? r.SimTime - f.LandTime : -1.0;
        }
    }

    /// <summary>中心周围 LocalR 像素里自己的领地占多少（隔一个像素取一个点）。</summary>
    private static double LocalShare(TerritoryField fld, Vector2 c, int team)
    {
        int cx = (int)c.X, cy = (int)c.Y, n = 0, mine = 0;
        for (int y = -LocalR; y <= LocalR; y += 2)
        {
            int yy = cy + y;
            if ((uint)yy >= TerritoryField.Size) continue;
            int half = (int)Math.Sqrt(LocalR * LocalR - y * y), row = yy * TerritoryField.Size;
            for (int x = -half; x <= half; x += 2)
            {
                int xx = cx + x;
                if ((uint)xx >= TerritoryField.Size) continue;
                n++;
                if (fld.Owner[row + xx] == team) mine++;
            }
        }
        return n > 0 ? (double)mine / n : 0.0;
    }

